const mineflayer = require('mineflayer')
const bot = mineflayer.createBot({ host: '127.0.0.1', port: 25565, username: 'Tester', version: '1.12.2' })
const lines = []
bot.on('message', (msg) => {
  const s = msg.toString()
  lines.push(s)
  console.log('[chat]', s)
})
bot.once('spawn', async () => {
  console.log('[brew-stack] spawned')
  bot.chat('/corebrew check')
  await new Promise(r => setTimeout(r, 1500))
  bot.chat('/corebrew reload')
  await new Promise(r => setTimeout(r, 1500))
  bot.chat('/corebrew check')
  await new Promise(r => setTimeout(r, 1500))
  const joined = lines.join('\n')
  const ok = /max_stack=127/.test(joined) && /stackLimits=true|defaultMaxStack=127/.test(joined)
  console.log(ok ? '[brew-stack] CHECK OK max_stack=127' : '[brew-stack] CHECK FAIL')
  bot.quit()
  process.exit(ok ? 0 : 1)
})
bot.on('error', (e) => { console.error(e); process.exit(1) })
setTimeout(() => { console.error('timeout'); process.exit(2) }, 25000)
